  u.id AS auth_user_uuid,
  u.email,
  (au.user_id IS NOT NULL) AS admin_registered
FROM auth.users AS u
LEFT JOIN public.admin_users AS au ON au.user_id = u.id
WHERE lower(u.email) = lower('REPLACE_WITH_YOUR_ADMIN_EMAIL');

